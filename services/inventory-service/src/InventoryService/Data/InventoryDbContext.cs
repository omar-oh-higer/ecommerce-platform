using Microsoft.EntityFrameworkCore;

namespace InventoryService.Data;

/// <summary>
/// The inventory service's own database. core-api never connects to it:
/// it only talks to this service through proto/inventory.proto.
/// </summary>
public class InventoryDbContext(DbContextOptions<InventoryDbContext> options) : DbContext(options)
{
    public DbSet<StockItem> StockItems => Set<StockItem>();
    public DbSet<Reservation> Reservations => Set<Reservation>();
    public DbSet<ReservationItem> ReservationItems => Set<ReservationItem>();

    protected override void OnModelCreating(ModelBuilder model)
    {
        model.Entity<StockItem>(e =>
        {
            e.ToTable("stock_items", t => t.HasCheckConstraint("ck_stock_items_quantity_not_negative", "quantity >= 0"));
            e.HasKey(x => x.ProductId);
            e.Property(x => x.ProductId).HasColumnName("product_id").ValueGeneratedNever();
            e.Property(x => x.Quantity).HasColumnName("quantity");
            e.Property(x => x.UpdatedAt).HasColumnName("updated_at");
        });

        model.Entity<Reservation>(e =>
        {
            e.ToTable("reservations");
            e.HasKey(x => x.Id);
            e.Property(x => x.Id).HasColumnName("id").HasMaxLength(64);
            e.Property(x => x.Status).HasColumnName("status").HasConversion<string>().HasMaxLength(20);
            e.Property(x => x.CreatedAt).HasColumnName("created_at");
            e.Property(x => x.ReleasedAt).HasColumnName("released_at");
            e.HasMany(x => x.Items).WithOne().HasForeignKey(x => x.ReservationId).OnDelete(DeleteBehavior.Cascade);
        });

        model.Entity<ReservationItem>(e =>
        {
            e.ToTable("reservation_items");
            e.HasKey(x => new { x.ReservationId, x.ProductId });
            e.Property(x => x.ReservationId).HasColumnName("reservation_id").HasMaxLength(64);
            e.Property(x => x.ProductId).HasColumnName("product_id");
            e.Property(x => x.Quantity).HasColumnName("quantity");
        });
    }
}

/// <summary>Units of one product available for sale.</summary>
public class StockItem
{
    public long ProductId { get; set; }
    public int Quantity { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}

public enum ReservationStatus
{
    Reserved,
    Released,
}

/// <summary>Stock held for one order (id generated by core-api).</summary>
public class Reservation
{
    public required string Id { get; set; }
    public ReservationStatus Status { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? ReleasedAt { get; set; }
    public List<ReservationItem> Items { get; set; } = [];
}

public class ReservationItem
{
    public required string ReservationId { get; set; }
    public long ProductId { get; set; }
    public int Quantity { get; set; }
}
